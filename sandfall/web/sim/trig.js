/** Sine of k 256ths of a turn, times 256 */
export function sin256(k) {
  return SIN[k & 255];
}

/** Cosine of k 256ths of a turn, times 256 */
export function cos256(k) {
  return SIN[(k + 64) & 255];
}

/** Sine of k 4096ths of a turn, times 256: the table, with whole-number blending between its entries */
export function sin4096(k) {
  const at = (k >> 4) & 255;
  return SIN[at] + (((SIN[(at + 1) & 255] - SIN[at]) * (k & 15)) >> 4);
}

/** Cosine of k 4096ths of a turn, times 256 */
export function cos4096(k) {
  return sin4096(k + 1024);
}

/** The whole-number square root of n (rounded down). Exact for every n below 2^53. */
export function isqrt(n) {
  if (n <= 0) {
    return 0;
  }
  let x = n;
  let y = Math.trunc((x + 1) / 2);
  while (y < x) {
    x = y;
    y = Math.trunc((x + Math.trunc(n / x)) / 2);
  }
  return x;
}
